"""Practical size of the effect near the acceptance threshold (main study, Claude, review form).

  python src/fig_borderline.py  -> paper/figs/fig_borderline.pdf/.png, paper/numbers_border.tex

a, share of papers Claude recommends for acceptance under the author and the reviewer ask, by the mean rating
   ICLR reviewers gave the paper (bins), with the share of papers that get opposite verdicts.
b, papers with opposite verdicts, borderline (human mean in [4, 6)) vs other papers, split by ICLR's decision.
Reads full_study/out/cells.csv; the borderline definition and the interaction test are those of stats_full.py
(numbers for the test are taken from stats.json, already BH-adjusted there).
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_figs as F  # noqa: E402  (style, colours, save)

ROOT = Path(__file__).resolve().parents[1]
plt = F.plt
BINS = [0, 3, 4, 5, 6, 7, 10]
BIN_LABEL = ["<3", "3–4", "4–5", "5–6", "6–7", "≥7"]
rng = np.random.default_rng(20261104)


def data():
    c = pd.read_csv(ROOT / "full_study" / "out" / "cells.csv")
    d = c[(c.model == "claude") & (c.fmt == "struct") & c.who.isin(["author", "reviewer"])]
    w = d.pivot_table(index="paper_id", columns="who", values="accept")
    w = w.join(d.groupby("paper_id")[["human_mean", "human_accept", "border"]].first()).dropna()
    w["ao"] = (w.author == 1) & (w.reviewer == 0)
    w["ro"] = (w.author == 0) & (w.reviewer == 1)
    w["bin"] = pd.cut(w.human_mean, BINS, right=False, labels=BIN_LABEL)
    return w


def rerun():
    """Noise floor: the same ask re-run in a later batch on the 100 retest papers (rep 0 vs rep 1, review form)."""
    ids = pd.read_csv(ROOT / "full_study" / "data" / "retest100.csv")
    hm = dict(ids[["paper_id", "human_mean"]].values)
    rows = []
    for line in open(ROOT / "full_study" / "results" / "p2_review_claude.jsonl"):
        r = json.loads(line)
        if not (r.get("ok") and r["paper_id"] in hm and str(r.get("relay", "")).startswith("https://api.sailapi")):
            continue
        fmt, who = r["condition"].split("_", 1)
        if fmt == "struct" and who in ("author", "reviewer") and r["rep"] in (0, 1):
            rows.append(dict(pid=r["paper_id"], who=who, rep=r["rep"], a=int(r["parsed"]["recommendation"] == "accept")))
    d = pd.DataFrame(rows).drop_duplicates(["pid", "who", "rep"], keep="last")
    w = d.pivot_table(index=["pid", "who"], columns="rep", values="a").dropna().reset_index()
    w["hm"] = w.pid.map(hm)
    b = w[(w.hm >= 4) & (w.hm < 6)]
    return {"rerun/flip": f"{(w[0] != w[1]).mean() * 100:.0f}\\%", "rerun/n": str(len(w)),
            "rerun/border/flip": f"{(b[0] != b[1]).mean() * 100:.0f}\\%", "rerun/border/n": str(len(b)),
            "rerun/up": str(int(((w[0] == 0) & (w[1] == 1)).sum())), "rerun/down": str(int(((w[0] == 1) & (w[1] == 0)).sum()))}


def boot_rd(s):
    x = (s.author - s.reviewer).to_numpy(float)
    bs = x[rng.integers(0, len(x), (10000, len(x)))].mean(1)
    return x.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def numbers(w):
    R = json.loads((ROOT / "full_study" / "out" / "stats.json").read_text())
    V = {}
    for name, s in (("border", w[w.border == 1]), ("other", w[w.border == 0])):
        rd, lo, hi = boot_rd(s)
        V[f"{name}/n"] = str(len(s))
        V[f"{name}/accA"] = f"{s.author.mean() * 100:.0f}\\%"
        V[f"{name}/accR"] = f"{s.reviewer.mean() * 100:.0f}\\%"
        V[f"{name}/rd"] = f"{rd * 100:.0f}"
        V[f"{name}/rdci"] = f"${rd * 100:+.0f}$ [${lo * 100:.0f}$, ${hi * 100:.0f}$]"
        V[f"{name}/ao"], V[f"{name}/ro"] = str(int(s.ao.sum())), str(int(s.ro.sum()))
        V[f"{name}/flip"] = f"{(s.ao | s.ro).mean() * 100:.0f}\\%"
        for h, k in ((0, "rej"), (1, "acc")):
            t = s[s.human_accept == h]
            V[f"{name}/{k}/n"] = str(len(t))
            V[f"{name}/{k}/ao"], V[f"{name}/{k}/ro"] = str(int(t.ao.sum())), str(int(t.ro.sum()))
    t = [x for x in R["secondary_tests"] if x["model"] == "claude" and x["contrast"] == "struct"
         and x["outcome"] == "accept author x borderline"][0]
    V["int/p"] = f"$p={t['p']:.3f}$"
    V["int/pbh"] = f"$p_{{\\mathrm{{BH}}}}={t['p_adj']:.3f}$"
    V["all/flip"] = f"{(w.ao | w.ro).mean() * 100:.0f}\\%"
    V["all/n"] = str(len(w))
    peak = w[w.human_mean.between(3, 6, inclusive="left")]
    V["peak/flip"] = f"{(peak.ao | peak.ro).mean() * 100:.0f}\\%"
    V["peak/n"] = str(len(peak))
    V.update(rerun())
    lines = ["% Generated by src/fig_borderline.py. Do not edit.", r"\makeatletter"]
    lines += [r"\@namedef{num@bd/%s}{%s}" % (k, v) for k, v in sorted(V.items())]
    lines.append(r"\makeatother")
    (ROOT / "paper" / "numbers_border.tex").write_text("\n".join(lines) + "\n")
    return V


def figure(w):
    fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.6), gridspec_kw={"width_ratios": [1.45, 1], "wspace": 0.42})

    ax = axes[0]
    g = w.groupby("bin", observed=True)
    x = np.arange(len(BIN_LABEL))
    accA, accR = g.author.mean().to_numpy(), g.reviewer.mean().to_numpy()
    n = g.size().to_numpy()
    ax.axvspan(1.5, 3.5, color=F.BAND, zorder=0, lw=0)
    ax.text(2.5, 1.06, "borderline", ha="center", va="top", fontsize=6.8, color=F.MUTED, style="italic")
    bw = 0.36
    ax.bar(x - bw / 2, accA, bw * 0.92, color=F.G2[0], edgecolor=F.INK, linewidth=0.5, zorder=3, label="I wrote it")
    ax.bar(x + bw / 2, accR, bw * 0.92, color=F.G2[1], edgecolor=F.INK, linewidth=0.5, zorder=3, label="I am reviewing it")
    for i in range(len(x)):
        ax.text(x[i] - bw / 2, accA[i] + 0.012, f"{accA[i] * 100:.0f}", ha="center", va="bottom", fontsize=6.2)
        ax.text(x[i] + bw / 2, accR[i] + 0.012, f"{accR[i] * 100:.0f}", ha="center", va="bottom", fontsize=6.2)
        ax.text(x[i], max(accA[i], accR[i]) + 0.075, f"{(accA[i] - accR[i]) * 100:+.0f}", ha="center", va="bottom",
                fontsize=6.6, color=F.INK, fontweight="bold")
    ax.set_xticks(x)
    ax.set_xticklabels([f"{b}\n(n={k})" for b, k in zip(BIN_LABEL, n)])
    ax.tick_params(axis="x", length=0)
    ax.set_xlabel("Mean rating by ICLR reviewers")
    ax.set_xlim(-0.5, len(x) - 0.5)
    ax.set_ylim(0, 1.08)
    ax.set_yticks([0, 0.25, 0.5, 0.75, 1.0])
    ax.set_yticklabels(["0", "25", "50", "75", "100"])
    for s_ in ("left", "top", "right", "bottom"):
        ax.spines[s_].set_visible(True)
    ax.tick_params(axis="y", width=0.6, length=2.5)
    ax.set_ylabel("Recommended for acceptance (%)")
    ax.grid(axis="y", color=F.GRID, lw=0.5, ls=(0, (3, 2)), zorder=0)
    ax.set_axisbelow(True)
    ax.legend(loc="lower left", bbox_to_anchor=(0, 1.0), ncol=2, handletextpad=0.3, columnspacing=1.2, borderaxespad=0.2)
    F.header(ax, "a", "Acceptance by the paper's standing with ICLR reviewers", y=1.16)

    ax = axes[1]
    rows = [("border", 0, "Borderline,\nrejected by ICLR"), ("border", 1, "Borderline,\naccepted by ICLR"),
            ("other", 0, "Other,\nrejected by ICLR"), ("other", 1, "Other,\naccepted by ICLR")]
    for i, (b, h, lab) in enumerate(rows):
        s = w[(w.border == (b == "border")) & (w.human_accept == h)]
        ao, ro = s.ao.mean(), s.ro.mean()
        ax.barh(i, ao * 100, 0.62, color=F.G2[0], edgecolor=F.INK, linewidth=0.5, zorder=3, label="Only the author's accepted" if i == 0 else None)
        ax.barh(i, -ro * 100, 0.62, color=F.G2[1], edgecolor=F.INK, linewidth=0.5, zorder=3, label="Only the reviewer's accepted" if i == 0 else None)
        ax.text(ao * 100 + 0.8, i, f"{int(s.ao.sum())}", va="center", ha="left", fontsize=6.6)
        ax.text(-ro * 100 - 0.8, i, f"{int(s.ro.sum())}", va="center", ha="right", fontsize=6.6)
        ax.text(37, i, f"n={len(s)}", va="center", ha="right", fontsize=6.4, color=F.MUTED)
    ax.axvline(0, color=F.INK, lw=0.6, zorder=4)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels([r[2] for r in rows])
    ax.set_ylim(len(rows) - 0.5, -0.5)
    ax.set_xlim(-12, 39.5)
    ax.set_xticks([-10, 0, 10, 20])
    ax.set_xticklabels(["10", "0", "10", "20"])
    ax.set_xlabel("Papers with opposite verdicts (%)")
    ax.grid(axis="x", color=F.GRID, lw=0.5, ls=(0, (3, 2)), zorder=0)
    ax.set_axisbelow(True)
    for s_ in ("left", "top", "right", "bottom"):
        ax.spines[s_].set_visible(True)
    ax.tick_params(axis="y", length=0)
    ax.legend(loc="lower left", bbox_to_anchor=(-0.02, 1.0), ncol=2, handletextpad=0.3, columnspacing=0.9, borderaxespad=0.2, handlelength=1.0)
    F.header(ax, "b", "Which papers flip", y=1.16)
    F.save(fig, "fig_borderline")


if __name__ == "__main__":
    w = data()
    V = numbers(w)
    figure(w)
    for k in sorted(V):
        print(k, V[k])
