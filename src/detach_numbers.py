"""Numbers for the third preregistered study (OSF 65qph): request to judge the paper as someone else's.

  python src/detach_numbers.py  -> paper/numbers_detach.tex (keys \\V{dt/...}), paper/tables/detach.tex

Registered results come only from the frozen analysis output (detach/results_seeta/detach_stats_sample.json, copied
from the run server). The raw answers in the same folder are read for counts only.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "detach" / "results_seeta"
OUT = ROOT / "paper" / "numbers_detach.tex"
TAB = ROOT / "paper" / "tables" / "detach.tex"


def s(x):
    return f"${x:+.2f}$"


def u(x):
    return f"${x:.2f}$"


def pv(p):
    return "$p<0.001$" if p < 0.001 else (f"$p={p:.3f}$" if p < 0.01 else f"$p={p:.2f}$")


def pct(x):
    return f"{x * 100:.0f}\\%"


def star(p):
    return "$^{***}$" if p < 0.001 else ("$^{**}$" if p < 0.01 else ("$^{*}$" if p < 0.05 else ""))


def grey(lo, hi):
    return f"{{\\scriptsize\\color{{black!60}}[{s(lo) if lo < 0 else u(lo)}, {s(hi) if hi < 0 else u(hi)}]}}"


def table(P, S, n):
    """Same layout as tables/mitig.tex: estimates on the first row, intervals in grey below."""
    h1, h2, h3 = P["H1"], P["H2"], P["H3"]
    w = [S["S1_by_wording"][f]["H3"] for f in ("W1", "W2", "W3")]
    b = lambda x: r"{\boldmath" + x + "}"
    L = [r"\begin{tabular}{@{}l rrr rrr c@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{Registered tests} & \multicolumn{3}{c}{H3 by wording} & Gap \\", r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
         r" & H1 author $-$ reviewer & H2 reduction & H3 remaining gap & W1 & W2 & W3 & closed \\", r"\midrule",
         "Claude Sonnet~4.6, review form & " + " & ".join([b(s(h1["est"])) + star(h1["p"]), b(s(h2["est"])) + star(h2["p"]), b(s(h3["est"]))]
                                                          + [s(x["est"]) for x in w]) + f" & {'yes' if P['closes_gap'] else 'no'} \\\\",
         f"\\quad {n} papers & " + " & ".join([grey(h1["lo"], h1["hi"]), grey(h2["lo"], h2["hi"]), grey(*h3["ci90"])]
                                              + [grey(*x["ci90"]) for x in w]) + " &  \\\\",
         r"\bottomrule", r"\end{tabular}"]
    TAB.write_text("\n".join(L) + "\n")


def main():
    R = json.loads((RES / "detach_stats_sample.json").read_text())
    P, S = R["primary"], R["secondary"]
    V = {"dt/n": str(R["n_papers"]), "dt/cells": f"{R['n_valid_cells']:,}"}
    for k in ("H1", "H2"):
        e = P[k]
        V[f"dt/{k}/ci"] = f"{s(e['est'])} [{u(e['lo'])}, {u(e['hi'])}]"
        V[f"dt/{k}/d"], V[f"dt/{k}/u"], V[f"dt/{k}/p"] = s(e["est"]), u(abs(e["est"])), pv(e["p"])
    e = P["H3"]
    V["dt/H3/ci"] = f"{s(e['est'])} [{u(e['lo'])}, {u(e['hi'])}]"
    V["dt/H3/ci90"] = f"{s(e['est'])} [{s(e['ci90'][0])}, {s(e['ci90'][1])}]"
    V["dt/H3/d"], V["dt/H3/u"] = s(e["est"]), u(abs(e["est"]))
    V["dt/H3/tost"] = f"$p_{{\\mathrm{{TOST}}}}={e['p_tost']:.3f}$"
    for f in ("W1", "W2", "W3"):
        w = S["S1_by_wording"][f]
        V[f"dt/{f}/H1/d"] = s(w["H1"]["est"])
        V[f"dt/{f}/H2/d"] = s(w["H2"]["est"])
        h = w["H3"]
        V[f"dt/{f}/H3/d"] = s(h["est"])
        V[f"dt/{f}/H3/ci90"] = f"{s(h['est'])} [{s(h['ci90'][0])}, {s(h['ci90'][1])}]"
    it = S["S1_interaction"]
    V["dt/int"] = f"$F={it['F']:.2f}$, {pv(it['p'])}"
    for w, x in S["S2_accept_rate"].items():
        V[f"dt/accept/{w.replace('_', '.')}"] = pct(x)
    for t, x in S["S2_flips"].items():
        a, b = [x[k] for k in x if k.endswith("_only")]
        V[f"dt/flips/{t}"] = f"{a} to {b}"
        V[f"dt/flips/{t}/p"] = pv(x["p"])
    for w, x in S["S3_mean_rating"].items():
        V[f"dt/mean/{w.replace('_', '.')}"] = f"{x:.2f}"
    V["dt/nrec"] = str(S["S4_without_recognized"]["n_recognized"])
    V["dt/major/H1/d"] = s(S["S7_subscores"]["major"]["H1"]["est"])
    V["dt/share"] = pct(P["H2"]["est"] / P["H1"]["est"])
    table(P, S, R["n_papers"])
    lines = ["% Generated by src/detach_numbers.py from detach/results_seeta/. Do not edit.", r"\makeatletter"]
    lines += [f"\\@namedef{{num@{k}}}{{{v}}}" for k, v in sorted(V.items())]
    lines += [r"\makeatother"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(V)} numbers -> {OUT}")


if __name__ == "__main__":
    main()
